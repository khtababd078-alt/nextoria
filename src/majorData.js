// Normalize Arabic text for flexible matching
function normalizeAr(str) {
  return str
    .trim()
    .replace(/\s+/g, ' ')
    .replace(/[أإآا]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .toLowerCase();
}

// Build normalized lookups once
const _normalized = {};
for (const [name, min] of Object.entries(MAJOR_MIN_SCORES)) {
  _normalized[normalizeAr(name)] = min;
}
const _normalizedDetails = {};
for (const [name, detail] of Object.entries(MAJOR_DETAILS)) {
  _normalizedDetails[normalizeAr(name)] = detail;
}

/**
 * Returns the minimum GPA required for a major.
 * Returns null if the major is not found in the database.
 */
export function getMajorMinScore(majorName) {
  if (!majorName) return null;
  // Try exact match first
  if (MAJOR_MIN_SCORES[majorName] !== undefined) return MAJOR_MIN_SCORES[majorName];
  // Try normalized match
  const key = normalizeAr(majorName);
  return _normalized[key] ?? null;
}

/**
 * Returns true if the student's GPA meets the minimum for this major.
 * If the major is not found in the database, returns true (allow it through).
 */
export function isEligible(majorName, studentGpa) {
  const min = getMajorMinScore(majorName);
  if (min === null) return true;
  return parseFloat(studentGpa) >= min;
}

