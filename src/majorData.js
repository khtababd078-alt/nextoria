const _fieldMajorsNorm = {};
for (const [field, majors] of Object.entries(FIELD_MAJORS)) {
  _fieldMajorsNorm[field] = new Set(majors.map(normalizeAr));
}

const _majorUniversitiesNorm = {};
for (const [major, unis] of Object.entries(MAJOR_UNIVERSITIES)) {
  _majorUniversitiesNorm[normalizeAr(major)] = unis;
}

// Keyword-based fallback — catches API name variants not in our exact list
const FIELD_KEYWORDS = {
  engineering:  ['هندسه', 'عماره'],
  health:       ['صيدله', 'تمريض', 'بصريات', 'اسعاف', 'اشعه', 'تغذيه'],
  science_tech: ['سيبراني', 'حاسوبيه', 'ذكاء اصطناعي'],
  business:     ['اداره اعمال', 'محاسبه اداريه'],
  law:          ['قانون'],
  humanities:   [],
};

export function isMajorInField(majorName, fieldId) {
  if (!fieldId || !majorName) return true;
  const norm = normalizeAr(majorName);

  // 1. Exact match in target field list → allow
  if (_fieldMajorsNorm[fieldId]?.has(norm)) return true;

  // 2. Keyword match for target field → allow (catches API name variations)
  const kws = FIELD_KEYWORDS[fieldId] || [];
  if (kws.some(kw => norm.includes(kw))) return true;

  // 3. Exact match in a DIFFERENT field → block
  for (const [fid, normSet] of Object.entries(_fieldMajorsNorm)) {
    if (fid !== fieldId && normSet.has(norm)) return false;
  }

  // 4. Unknown major (not in any list) → reject when a specific field is selected
  return false;
}

export function getMajorUniversities(majorName, fieldId) {
  if (!majorName) return (FIELD_DEFAULT_UNIVERSITIES[fieldId] || []).slice(0, 3);
  if (MAJOR_UNIVERSITIES[majorName]) return MAJOR_UNIVERSITIES[majorName].slice(0, 3);
  const norm = normalizeAr(majorName);
  if (_majorUniversitiesNorm[norm]) return _majorUniversitiesNorm[norm].slice(0, 3);
  // Prefix match for short API names
  let bestUnis = null;
  let bestDiff = Infinity;
  for (const [normKey, unis] of Object.entries(_majorUniversitiesNorm)) {
    if (normKey.startsWith(norm + ' ')) {
      const diff = normKey.length - norm.length;
      if (diff < bestDiff) { bestDiff = diff; bestUnis = unis; }
    } else if (norm.startsWith(normKey + ' ')) {
      const diff = norm.length - normKey.length;
      if (diff < bestDiff) { bestDiff = diff; bestUnis = unis; }
    }
  }
  if (bestUnis) return bestUnis.slice(0, 3);
  return (FIELD_DEFAULT_UNIVERSITIES[fieldId] || []).slice(0, 3);
}

// Score for sorting: prefer where student GPA is at or just above competitive avg.
// Positive fit (student above): sort ascending (0 = ideal, bigger = easier major).
// Negative fit (student below): penalized heavily; less negative = less risky.
function _compScore(studentGpa, expected) {
  const fit = studentGpa - expected;
  return fit >= 0 ? fit : 1000 + (-fit);
}

export function getFieldFallbackMajors(fieldId, studentGpa, excludeNames = []) {
  const gpa = parseFloat(studentGpa) || 0;
  const excludeNorm = new Set(excludeNames.map(normalizeAr));
  const TOLERANCE = 7; // max expected GPA above student before we consider it unrealistic

  const filtered = Object.entries(MAJOR_DETAILS)
    .filter(([name, d]) => {
      if (excludeNorm.has(normalizeAr(name))) return false;
      if (!isMajorInField(name, fieldId)) return false;
      const min = getMajorMinScore(name);
      if (min !== null && gpa < min) return false;
      if (d.expected && d.expected > gpa + TOLERANCE) return false;
      return true;
    })
    .sort((a, b) => _compScore(gpa, a[1].expected) - _compScore(gpa, b[1].expected))
    .map(([name]) => name);

  // If nothing passes the tolerance, relax it (show closest options regardless)
  if (filtered.length === 0) {
    return Object.entries(MAJOR_DETAILS)
      .filter(([name]) => {
        if (excludeNorm.has(normalizeAr(name))) return false;
        if (!isMajorInField(name, fieldId)) return false;
        const min = getMajorMinScore(name);
        return min === null || gpa >= min;
      })
      .sort((a, b) => _compScore(gpa, a[1].expected) - _compScore(gpa, b[1].expected))
      .map(([name]) => name);
  }
  return filtered;
}
