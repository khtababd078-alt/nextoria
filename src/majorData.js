export function getMajorDetails(majorName) {
  if (!majorName) return null;
  if (MAJOR_DETAILS[majorName]) return MAJOR_DETAILS[majorName];
  const key = normalizeAr(majorName);
  return _normalizedDetails[key] ?? null;
}
